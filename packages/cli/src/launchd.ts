import { join } from 'node:path';

/**
 * The launchd job that replaces the `aion-mcp` compose service on a native install, and the
 * template it is rendered from. It is a string built here rather than a file on disk because
 * every value in it is a path this machine resolved: the node binary running init, the repo the
 * server was built in, and the log directory the config names.
 *
 * What compose gave the service, and where each of those comes from here:
 *
 * - `restart: unless-stopped` becomes `KeepAlive`, with `RunAtLoad` so a login starts it.
 * - `stop_grace_period: 20s` becomes `ExitTimeOut`. The service drains tool calls already
 *   running before it closes the driver and SQLite, and the supervisor's own default is what
 *   would otherwise kill it partway through that drain.
 * - `env_file: .env` becomes `EnvironmentVariables`. A launchd job inherits almost nothing, and
 *   nothing in this build reads `.env` on the host, so the file's `AION_*` values are rendered
 *   into the job. That is also why the job is regenerated by `aion init`: a `.env` edited
 *   afterwards does not reach a loaded job until init writes it again and it is restarted.
 * - the capped json-file log driver has no equivalent, and needs none. The service's own file
 *   logger holds the durable JSONL copy, so the stdout tee goes to /dev/null rather than to a
 *   second unbounded file nothing rotates. stderr does get a file: a failure before the logger
 *   opens is reported there and nowhere else.
 */

export const MCP_LAUNCH_LABEL = 'com.aion.mcp';

/** The compose `stop_grace_period`, in the units launchd takes. */
export const MCP_EXIT_TIMEOUT_SECONDS = 20;

export const MCP_SCRIPT_RELATIVE = join('packages', 'mcp', 'dist', 'main.js');

export function launchAgentPath(home: string): string {
  return join(home, 'Library', 'LaunchAgents', `${MCP_LAUNCH_LABEL}.plist`);
}

export function mcpScriptPath(repoDir: string): string {
  return join(repoDir, MCP_SCRIPT_RELATIVE);
}

export type LaunchdJob = {
  readonly nodePath: string;
  readonly repoDir: string;
  /** `AION_*` pairs, in the order they are rendered. Empty values are the caller's to drop. */
  readonly environment: readonly (readonly [string, string])[];
  readonly standardErrorPath: string;
};

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function environmentBlock(environment: readonly (readonly [string, string])[]): string {
  if (environment.length === 0) {
    return '';
  }
  const pairs = environment
    .map(
      ([key, value]) =>
        `    <key>${escapeXml(key)}</key>\n    <string>${escapeXml(value)}</string>`,
    )
    .join('\n');
  return `  <key>EnvironmentVariables</key>\n  <dict>\n${pairs}\n  </dict>\n`;
}

/**
 * The rendered job. The comment at the top is deliberate: the file lands in a directory an
 * operator edits by hand, and the next person to open it needs to know that init rewrites it.
 */
export function renderLaunchdPlist(job: LaunchdJob): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Written by \`aion init --profile native\` from ${escapeXml(join(job.repoDir, '.env'))}.
     Edits here are lost the next time init runs; change .env and re-run it instead. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${MCP_LAUNCH_LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>${escapeXml(job.nodePath)}</string>
    <string>${escapeXml(mcpScriptPath(job.repoDir))}</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${escapeXml(job.repoDir)}</string>
${environmentBlock(job.environment)}  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ExitTimeOut</key>
  <integer>${String(MCP_EXIT_TIMEOUT_SECONDS)}</integer>
  <key>StandardOutPath</key>
  <string>/dev/null</string>
  <key>StandardErrorPath</key>
  <string>${escapeXml(job.standardErrorPath)}</string>
</dict>
</plist>
`;
}

/**
 * The three commands for the job by hand: init runs the first itself, and prints all three where
 * it could not. The restart is the one an operator needs most often, after a rebuild, since the
 * job holds the built server rather than a container image.
 */
export function launchdCommands(plistPath: string): readonly string[] {
  return [
    `launchctl bootstrap gui/$(id -u) ${plistPath}`,
    `launchctl kickstart -k gui/$(id -u)/${MCP_LAUNCH_LABEL}   # restart after a rebuild`,
    `launchctl bootout gui/$(id -u) ${plistPath}               # stop and unload`,
  ];
}
